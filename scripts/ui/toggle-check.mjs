import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []; page.on('pageerror', (e) => errors.push(e.message))
await page.goto('http://localhost:5010/', { waitUntil: 'load' }); await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'Add', exact: true }).click(); await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Add' }).nth(1).click(); await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Edit' }).first().click(); await page.waitForTimeout(1500)
const h = () => page.locator('.blockly-host').evaluate((e) => Math.round(e.getBoundingClientRect().height))
console.log('open height', await h())
await page.getByRole('button', { name: /Hide details/ }).click(); await page.waitForTimeout(800)
console.log('collapsed height', await h(), 'card visible', await page.locator('input[placeholder="Name"]').isVisible())
await page.screenshot({ path: 'screenshots/collapsed.png' })
console.log('errors', errors)
await browser.close()
